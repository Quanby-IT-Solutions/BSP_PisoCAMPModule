import { Buffer } from "node:buffer"

/**
 * CE-2 neutral coin model.
 *
 * A deliberately fictional, procedurally generated coin: a reeded cylinder with
 * two abstract, non-functional face motifs. It represents *the idea of a coin*
 * so the 3D viewer can be exercised for every mandatory denomination without
 * reproducing, imitating or implying any real circulating coin. It carries no
 * text, numerals, portraits, emblems, seals or mint marks.
 *
 * Every value below is produced by exact IEEE-754 addition, subtraction,
 * multiplication and square root from decimal literals — no library
 * transcendental is called — so the bytes are bit-identical on every platform
 * that runs the generator. The checked-in seed bundle depends on that: it is
 * validated by regenerating it and comparing bytes.
 */

/** Segments around the circumference. Also the number of edge reeds. */
const SEGMENTS = 128
/** cos(2π/128) and sin(2π/128), as exact shortest-round-trip doubles. */
const STEP_COS = 0.9987954562051724
const STEP_SIN = 0.049067674327418015

const HALF_THICKNESS = 0.08
/** Reed peaks and valleys alternate around the edge. */
const REED_PEAK_RADIUS = 1
const REED_VALLEY_RADIUS = 0.975

type Rgba = readonly [number, number, number, number]
type Point = readonly [number, number]

interface FaceDesign {
	/** Concentric band boundaries, innermost first; the outer edge is implicit. */
	readonly radii: readonly number[]
	readonly bandColors: readonly Rgba[]
	/** Index into `bandColors` of the band carrying the alternating motif. */
	readonly motifBand: number
	readonly motifColor: Rgba
	/** Alternating sectors around the motif band. Even values keep it symmetric. */
	readonly motifSectors: number
}

const OBVERSE: FaceDesign = {
	radii: [0.18, 0.34, 0.52, 0.72, 0.9],
	bandColors: [
		[214, 176, 102, 255],
		[198, 158, 88, 255],
		[222, 190, 124, 255],
		[206, 166, 94, 255],
		[196, 156, 86, 255],
		[216, 182, 112, 255],
	],
	motifBand: 3,
	motifColor: [232, 204, 146, 255],
	motifSectors: 24,
}

const REVERSE: FaceDesign = {
	radii: [0.24, 0.4, 0.58, 0.74, 0.9],
	bandColors: [
		[198, 204, 212, 255],
		[176, 184, 196, 255],
		[210, 216, 224, 255],
		[186, 194, 206, 255],
		[172, 180, 192, 255],
		[200, 208, 218, 255],
	],
	motifBand: 2,
	motifColor: [226, 232, 240, 255],
	motifSectors: 16,
}

const REED_PEAK_COLOR: Rgba = [188, 168, 128, 255]
const REED_VALLEY_COLOR: Rgba = [160, 142, 106, 255]

/**
 * Unit-circle samples generated by repeated complex multiplication by a fixed
 * step and renormalised with `Math.sqrt`. Both operations are exactly specified
 * by IEEE-754, so the table is reproducible bit for bit.
 */
function unitCircle(): Point[] {
	const points: Point[] = []
	let x = 1
	let y = 0
	for (let index = 0; index < SEGMENTS; index += 1) {
		const length = Math.sqrt(x * x + y * y)
		points.push([x / length, y / length])
		const nextX = x * STEP_COS - y * STEP_SIN
		const nextY = x * STEP_SIN + y * STEP_COS
		x = nextX
		y = nextY
	}
	return points
}

class MeshBuilder {
	readonly positions: number[] = []
	readonly normals: number[] = []
	readonly colors: number[] = []
	readonly indices: number[] = []

	private vertex(point: readonly number[], normal: readonly number[], color: Rgba): number {
		const index = this.positions.length / 3
		this.positions.push(point[0] ?? 0, point[1] ?? 0, point[2] ?? 0)
		this.normals.push(normal[0] ?? 0, normal[1] ?? 0, normal[2] ?? 0)
		this.colors.push(color[0], color[1], color[2], color[3])
		return index
	}

	/** Flat-shaded triangle: its own three vertices carrying the face normal. */
	triangle(
		a: readonly number[],
		b: readonly number[],
		c: readonly number[],
		normal: readonly number[],
		color: Rgba
	): void {
		const first = this.vertex(a, normal, color)
		this.vertex(b, normal, color)
		this.vertex(c, normal, color)
		this.indices.push(first, first + 1, first + 2)
	}

	quad(
		a: readonly number[],
		b: readonly number[],
		c: readonly number[],
		d: readonly number[],
		normal: readonly number[],
		color: Rgba
	): void {
		this.triangle(a, b, c, normal, color)
		this.triangle(a, c, d, normal, color)
	}
}

function reedRadius(segment: number): number {
	return segment % 2 === 0 ? REED_PEAK_RADIUS : REED_VALLEY_RADIUS
}

function crossNormal(
	a: readonly number[],
	b: readonly number[],
	c: readonly number[]
): readonly number[] {
	const ux = (b[0] ?? 0) - (a[0] ?? 0)
	const uy = (b[1] ?? 0) - (a[1] ?? 0)
	const uz = (b[2] ?? 0) - (a[2] ?? 0)
	const vx = (c[0] ?? 0) - (a[0] ?? 0)
	const vy = (c[1] ?? 0) - (a[1] ?? 0)
	const vz = (c[2] ?? 0) - (a[2] ?? 0)
	const nx = uy * vz - uz * vy
	const ny = uz * vx - ux * vz
	const nz = ux * vy - uy * vx
	const length = Math.sqrt(nx * nx + ny * ny + nz * nz)
	if (length === 0) return [0, 0, 1]
	return [nx / length, ny / length, nz / length]
}

function bandColor(design: FaceDesign, band: number, segment: number): Rgba {
	const base = design.bandColors[band] ?? design.bandColors[0]
	if (base === undefined) throw new Error("coin_model_band_color_missing")
	if (band !== design.motifBand) return base
	const sector = Math.floor((segment * design.motifSectors) / SEGMENTS)
	return sector % 2 === 0 ? base : design.motifColor
}

/**
 * One face of the coin. `sign` is +1 for the obverse (facing +Z) and -1 for the
 * reverse, which also reverses the winding so both faces stay outward-facing.
 */
function buildFace(mesh: MeshBuilder, circle: readonly Point[], design: FaceDesign, sign: 1 | -1) {
	const z = HALF_THICKNESS * sign
	const normal = [0, 0, sign]
	const centre = [0, 0, z]
	const innerRadius = design.radii[0]
	if (innerRadius === undefined) throw new Error("coin_model_radii_empty")

	const at = (segment: number, radius: number) => {
		const point = circle[segment % SEGMENTS]
		if (point === undefined) throw new Error("coin_model_circle_missing")
		return [point[0] * radius, point[1] * radius, z]
	}

	for (let segment = 0; segment < SEGMENTS; segment += 1) {
		const colour = bandColor(design, 0, segment)
		const first = at(segment, innerRadius)
		const second = at(segment + 1, innerRadius)
		if (sign === 1) mesh.triangle(centre, first, second, normal, colour)
		else mesh.triangle(centre, second, first, normal, colour)
	}

	for (let band = 0; band < design.radii.length; band += 1) {
		const inner = design.radii[band]
		if (inner === undefined) continue
		const outer = design.radii[band + 1]
		for (let segment = 0; segment < SEGMENTS; segment += 1) {
			// The outermost band meets the reeded edge, so its outer radius
			// follows the reed profile and the surface stays watertight.
			const outerHere = outer ?? reedRadius(segment)
			const outerNext = outer ?? reedRadius(segment + 1)
			const colour = bandColor(design, band + 1, segment)
			const a = at(segment, inner)
			const b = at(segment + 1, inner)
			const c = at(segment + 1, outerNext)
			const d = at(segment, outerHere)
			// Walking outwards first keeps the ring counter-clockwise seen from
			// +Z, which is the winding the centre fan already uses and the one a
			// renderer needs to treat the face as front-facing.
			if (sign === 1) mesh.quad(a, d, c, b, normal, colour)
			else mesh.quad(a, b, c, d, normal, colour)
		}
	}
}

/** The reeded edge: alternating peaks and valleys, flat-shaded per facet. */
function buildEdge(mesh: MeshBuilder, circle: readonly Point[]): void {
	for (let segment = 0; segment < SEGMENTS; segment += 1) {
		const here = circle[segment % SEGMENTS]
		const next = circle[(segment + 1) % SEGMENTS]
		if (here === undefined || next === undefined) continue
		const radiusHere = reedRadius(segment)
		const radiusNext = reedRadius(segment + 1)
		const top = [here[0] * radiusHere, here[1] * radiusHere, HALF_THICKNESS]
		const topNext = [next[0] * radiusNext, next[1] * radiusNext, HALF_THICKNESS]
		const bottomNext = [next[0] * radiusNext, next[1] * radiusNext, -HALF_THICKNESS]
		const bottom = [here[0] * radiusHere, here[1] * radiusHere, -HALF_THICKNESS]
		const normal = crossNormal(top, bottom, bottomNext)
		mesh.quad(
			top,
			bottom,
			bottomNext,
			topNext,
			normal,
			segment % 2 === 0 ? REED_PEAK_COLOR : REED_VALLEY_COLOR
		)
	}
}

function alignTo4(value: number): number {
	return (4 - (value % 4)) % 4
}

/**
 * Builds the binary glTF. The document is intentionally minimal — one buffer,
 * one mesh, one primitive, no textures, no animations — so a client can parse
 * it with a small strict reader rather than a general glTF loader.
 */
export function buildNeutralCoinModel(): Buffer {
	const circle = unitCircle()
	const mesh = new MeshBuilder()
	buildFace(mesh, circle, OBVERSE, 1)
	buildFace(mesh, circle, REVERSE, -1)
	buildEdge(mesh, circle)

	const vertexCount = mesh.positions.length / 3
	if (vertexCount > 65535) throw new Error("coin_model_too_many_vertices")

	const positions = Float32Array.from(mesh.positions)
	const normals = Float32Array.from(mesh.normals)
	const colors = Uint8Array.from(mesh.colors)
	const indices = Uint16Array.from(mesh.indices)

	let min = [Infinity, Infinity, Infinity]
	let max = [-Infinity, -Infinity, -Infinity]
	for (let index = 0; index < positions.length; index += 3) {
		min = min.map((value, axis) => Math.min(value, positions[index + axis] ?? 0))
		max = max.map((value, axis) => Math.max(value, positions[index + axis] ?? 0))
	}

	const positionBytes = Buffer.from(positions.buffer, positions.byteOffset, positions.byteLength)
	const normalBytes = Buffer.from(normals.buffer, normals.byteOffset, normals.byteLength)
	const colorBytes = Buffer.from(colors.buffer, colors.byteOffset, colors.byteLength)
	const indexBytes = Buffer.from(indices.buffer, indices.byteOffset, indices.byteLength)
	const indexPadding = alignTo4(indexBytes.byteLength)
	const binary = Buffer.concat([
		positionBytes,
		normalBytes,
		colorBytes,
		indexBytes,
		Buffer.alloc(indexPadding),
	])

	const positionOffset = 0
	const normalOffset = positionBytes.byteLength
	const colorOffset = normalOffset + normalBytes.byteLength
	const indexOffset = colorOffset + colorBytes.byteLength

	const gltf = {
		asset: { version: "2.0", generator: "pisocamp-neutral-coin/1" },
		scene: 0,
		scenes: [{ nodes: [0] }],
		nodes: [{ mesh: 0, name: "neutral-coin" }],
		meshes: [
			{
				name: "neutral-coin",
				primitives: [
					{ attributes: { POSITION: 0, NORMAL: 1, COLOR_0: 2 }, indices: 3, material: 0, mode: 4 },
				],
			},
		],
		materials: [
			{
				name: "neutral-coin-metal",
				pbrMetallicRoughness: {
					baseColorFactor: [1, 1, 1, 1],
					metallicFactor: 0.9,
					roughnessFactor: 0.35,
				},
				doubleSided: false,
			},
		],
		accessors: [
			{
				bufferView: 0,
				componentType: 5126,
				count: vertexCount,
				type: "VEC3",
				min,
				max,
			},
			{ bufferView: 1, componentType: 5126, count: vertexCount, type: "VEC3" },
			{ bufferView: 2, componentType: 5121, count: vertexCount, type: "VEC4", normalized: true },
			{ bufferView: 3, componentType: 5123, count: indices.length, type: "SCALAR" },
		],
		bufferViews: [
			{ buffer: 0, byteOffset: positionOffset, byteLength: positionBytes.byteLength, target: 34962 },
			{ buffer: 0, byteOffset: normalOffset, byteLength: normalBytes.byteLength, target: 34962 },
			{ buffer: 0, byteOffset: colorOffset, byteLength: colorBytes.byteLength, target: 34962 },
			{ buffer: 0, byteOffset: indexOffset, byteLength: indexBytes.byteLength, target: 34963 },
		],
		buffers: [{ byteLength: binary.byteLength }],
	}

	const jsonBytes = Buffer.from(JSON.stringify(gltf), "utf8")
	const jsonPadding = alignTo4(jsonBytes.byteLength)
	const jsonChunk = Buffer.concat([jsonBytes, Buffer.alloc(jsonPadding, 0x20)])

	const header = Buffer.alloc(12)
	header.write("glTF", 0, "ascii")
	header.writeUInt32LE(2, 4)
	header.writeUInt32LE(12 + 8 + jsonChunk.byteLength + 8 + binary.byteLength, 8)

	const jsonHeader = Buffer.alloc(8)
	jsonHeader.writeUInt32LE(jsonChunk.byteLength, 0)
	jsonHeader.write("JSON", 4, "ascii")

	const binaryHeader = Buffer.alloc(8)
	binaryHeader.writeUInt32LE(binary.byteLength, 0)
	binaryHeader.writeUInt32LE(0x004e4942, 4)

	return Buffer.concat([header, jsonHeader, jsonChunk, binaryHeader, binary])
}
